/** Spread the service's total duration over its steps (authority steps take the remainder) when a step has no explicit days. */
function withStepDays(entry: CatalogEntry): CatalogEntry {
  if (entry.steps.every((s) => s.days)) return entry;
  const base = Math.max(1, Math.floor(entry.estimated_days / entry.steps.length));
  let remainder = Math.max(0, entry.estimated_days - base * entry.steps.length);
  const steps = entry.steps.map((s) => ({ ...s, days: s.days ?? base }));
  for (const step of steps) {
    if (remainder === 0) break;
    if (step.owner === 'authority') {
      const extra = Math.ceil(remainder / Math.max(1, steps.filter((x) => x.owner === 'authority').length));
      step.days = (step.days ?? 0) + extra;
      remainder -= extra;
    }
  }
  if (remainder > 0) steps[steps.length - 1].days = (steps[steps.length - 1].days ?? 0) + remainder;
  return { ...entry, steps, estimated_days: steps.reduce((sum, s) => sum + (s.days ?? 0), 0) };
}

